// Copy the pack belonging to the person in front of this session out of the store and into
// this repository's session pack root, where the engine's loader finds it.
//
// WHY A WHOLE PACK AND NOT A FILE. What a person wants a session to know is not only prose.
// It is a skill they reach for, a check that catches the mistake they keep making, a
// requirement their tooling needs installed. Every one of those already has a carrier, the
// pack, with an engine that mounts, runs and reports it. Copying a pack gets all of them at
// once; a preferences file could only ever carry the first.
//
// IT WRITES INTO `.claudinite/temp/packs/current_user/` and reports nothing. The directory is
// the whole interface: the loader reads it, `session-start.mjs` reads it to say what landed,
// and a session that failed to copy leaves the same directory holding the placeholder. There
// is no status file, because everything a reader needs is either in the directory or is a
// pure function of the config and the environment (user_pack_address.mjs's `declineReason`).
//
// LOCAL FIRST. When this tree IS the store, the working copy is what the owner is reading and
// editing, and a clone would serve the default branch and quietly hide the edit in progress.
//
// FAIL-SOFT THROUGHOUT. No identity, no configured store, no directory for this person, a
// clone that fails: the placeholder stays and the session proceeds on default interaction
// behaviour. Nothing here is load-bearing, since the packs, checks and skills a session needs
// are already local.
//
// WHAT IT WILL WRITE, and nothing else: Markdown, JavaScript modules and JSON, under one
// directory, within a file count and byte budget. A pack is executable code that will run
// inside this session's hooks, so the store repository is as trusted as this one; that is
// stated in the pack's README, because no cap here can substitute for it.

import { existsSync, mkdirSync, readFileSync, writeFileSync, readdirSync, statSync, mkdtempSync } from 'node:fs';
import { join, dirname, relative, sep } from 'node:path';
import { tmpdir } from 'node:os';
import { spawnSync } from 'node:child_process';
import { removeTree } from '../../engine/remove-tree.mjs';
import { resolveStore, packDirFor, declineReason } from './user_pack_address.mjs';

const CLONE_TIMEOUT_MS = 60_000;

// The budget a person's pack is copied within. Generous for what a pack is, small enough that
// a mistake in the store cannot fill a session's disk or its context.
const MAX_FILES = 60;
const MAX_BYTES = 512 * 1024;
const COPYABLE = /\.(md|mjs|json)$/;

// Where the copy lands. The engine owns the name (engine/pack_loader/pack-registry.mjs); it is
// spelled here rather than imported because a member's vendored engine may predate the
// constant, and a step that fails to import is a step that never ran.
const PACK_DIR = join('.claudinite', 'temp', 'packs', 'current_user');

// The session root ignores itself. A member's own .gitignore may say nothing about it, and a
// self-ignoring file reaches every member on its next session with no edit of theirs.
const SESSION_ROOT_GITIGNORE = `# GENERATED by claude-code-web-users-support: session state, copied in every session
# start. Not tracked.
*
`;

export const packDirIn = (root) => join(root, PACK_DIR);
export const proseIn = (root) => join(packDirIn(root), 'RULES.md');

// What the prose file says when no pack was copied. It is written rather than left absent
// because the rules index imports that path literally in every session of a repo with this
// feature, and an import with no file behind it has no defined behaviour on the memory
// channel and no way to report one. Its exact text is how `session-start.mjs` tells "nothing
// landed" from "here are your rules".
export const PLACEHOLDER = '<!-- No personal pack was copied into this session. -->\n';

// The manifest the copied pack runs under when the person's own directory carries none, which
// is the ordinary case: someone with rules to state should not have to write a manifest to
// state them. Their own `pack.mjs` is copied untouched when they have one, and it must set
// neither `id`, which the engine takes from the directory and this directory is the session's,
// nor `version`, which a pack distributed to nobody has nothing to hold.
const SYNTHESIZED_MANIFEST = `// GENERATED by claude-code-web-users-support: the manifest the person's own pack
// directory did not carry. Edit nothing here, it is rewritten every session.
export default {
  ruleRoutingGuidance: {
    belongs: 'how this person wants to be worked with, in every project they work in',
    excludes: 'a project\\'s own conventions, which belong to the packs that own each subject',
  },
};
`;

// Every file under a directory in this tree, as paths relative to it.
function treeFiles(absDir, prefix = '') {
  const out = [];
  for (const entry of readdirSync(absDir, { withFileTypes: true })) {
    if (entry.name === '.git') continue;
    const rel = prefix ? `${prefix}/${entry.name}` : entry.name;
    if (entry.isDirectory()) out.push(...treeFiles(join(absDir, entry.name), rel));
    else if (entry.isFile()) out.push(rel);
  }
  return out;
}

// One git call, with its own clock, reporting the line git ended on.
function git(args, cwd) {
  const run = spawnSync('git', args, { cwd, encoding: 'utf8', timeout: CLONE_TIMEOUT_MS });
  if (run.error?.code === 'ETIMEDOUT') throw new Error(`git ${args[0]} did not finish in ${Math.round(CLONE_TIMEOUT_MS / 1000)}s`);
  if (run.status !== 0) throw new Error((run.stderr || `git ${args[0]} exited ${run.status}`).trim().split('\n').pop());
}

// The store's default branch with only this person's directory checked out, in a directory the
// caller removes. A CLONE and not a download: this repository's own experience is that codeload
// and the repo-scoped API are both denied by the sandbox proxy where git against the same
// repository is not, and a private store is reachable at all only through the credentials git
// is already configured with. Shallow and blob-filtered, so what it costs is one person's
// directory rather than the store's history.
function checkout(store, packDir) {
  const dir = mkdtempSync(join(tmpdir(), 'claudinite-personal-pack-'));
  git(['clone', '--depth', '1', '--filter=blob:none', '--sparse',
    process.env.CLAUDINITE_USER_PACKS_CLONE_URL || `https://github.com/${store.repo}`, dir]);
  git(['sparse-checkout', 'set', '--no-cone', packDir], dir);
  return dir;
}

// Leave the directory holding nothing but the placeholder: what every miss converges on, and
// what the very first session in a container starts from.
function leavePlaceholder(dest) {
  try {
    mkdirSync(dest, { recursive: true });
    if (!existsSync(join(dest, 'RULES.md'))) writeFileSync(join(dest, 'RULES.md'), PLACEHOLDER);
  } catch { /* an unwritable temp root is reported by the step, which can name itself */ }
}

// Copy this session's person's pack into `root`'s session pack root. Returns nothing a caller
// branches on: the directory is the answer, and the reasons a session gets no pack are a pure
// function of its config and environment. Throws only what the caller means to log.
export function copyUserPackToRepo({ root, config, env }) {
  const dest = packDirIn(root);
  try {
    const sessionRoot = join(root, '.claudinite', 'temp');
    mkdirSync(sessionRoot, { recursive: true });
    writeFileSync(join(sessionRoot, '.gitignore'), SESSION_ROOT_GITIGNORE);
  } catch { /* an unwritable temp root is reported by the step, which can name itself */ }
  const store = resolveStore(config);
  if (declineReason(config, env) !== null) return leavePlaceholder(dest);

  const packDir = packDirFor(store, env.CLAUDE_CODE_USER_EMAIL);
  let clone = null;
  let source = join(root, packDir);
  try {
    if (!existsSync(source)) {
      clone = checkout(store, packDir);
      source = join(clone, packDir);
    }
    if (!existsSync(source) || !statSync(source).isDirectory()) return leavePlaceholder(dest);

    const wanted = treeFiles(source).filter((p) => COPYABLE.test(p) && !p.split('/').includes('..'));
    if (!wanted.length || wanted.length > MAX_FILES) return leavePlaceholder(dest);

    // Empty the directory before writing. A pack left by an earlier session in this container,
    // for an earlier person or an earlier version of this one's, is content nobody here chose.
    // The root is the engine's session state and this pack's own subdirectory within it, so
    // nothing tracked is ever at risk.
    removeTree(dest);
    mkdirSync(dest, { recursive: true });

    let bytes = 0;
    let wroteManifest = false;
    for (const rel of wanted) {
      const content = readFileSync(join(source, rel));
      bytes += content.length;
      if (bytes > MAX_BYTES) { removeTree(dest); return leavePlaceholder(dest); }

      // Path-checked against the destination it claims to sit in.
      const target = join(dest, rel);
      const inside = relative(dest, target);
      if (inside.startsWith('..') || inside.startsWith(sep) || inside === '') continue;
      mkdirSync(dirname(target), { recursive: true });
      writeFileSync(target, content);
      if (rel === 'pack.mjs') wroteManifest = true;
    }
    if (!wroteManifest) writeFileSync(join(dest, 'pack.mjs'), SYNTHESIZED_MANIFEST);
    leavePlaceholder(dest); // a pack with no RULES.md of its own still needs the imported file
  } catch (e) {
    leavePlaceholder(dest);
    throw e;
  } finally {
    if (clone) { try { removeTree(clone); } catch { /* it outlives the session at worst */ } }
  }
}
