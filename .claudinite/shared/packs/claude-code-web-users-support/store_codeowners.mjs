// The store's CODEOWNERS block, derived from its person directories, so the check
// (`preferences-store-codeowners`, in Go) and the writer (write_store_codeowners.mjs) compute the
// same text. In the order GitHub's last-match-wins rule needs:
//
//   /<path>/                  @<admin>              a new directory needs the admin's approval
//   /<path>/<login>/          @<login> @<admin>     one per person
//   /.github/CODEOWNERS       @<admin>
//
// The admin sits beside each person because GitHub never counts a PR's author as a code
// owner's approval. The admin is the store repo's owning account.

export const DEFAULT_PATH = 'preferences';

// `{ repo, path }` when this pack's entry config names a usable store, else null: `repo`
// is `owner/name`, `path` the directory the people sit in, default `preferences`. The
// engine's session step reads the same address to copy a person's pack in.
export function resolveStore(config) {
  if (config === null || typeof config !== 'object' || Array.isArray(config)) return null;
  if (typeof config.repo !== 'string' || !/^[^/\s]+\/[^/\s]+$/.test(config.repo)) return null;
  if (config.path !== undefined && (typeof config.path !== 'string' || config.path.includes('..') || config.path.startsWith('/'))) return null;
  const path = (config.path ?? DEFAULT_PATH).replace(/^\.\/+|\/+$/g, '');
  return { repo: config.repo, path: path || DEFAULT_PATH };
}

// A GitHub login in lower case, the one spelling a person's directory takes; it becomes a
// path segment, so it is held to GitHub's own rule.
export const isUsableIdentity = (name) => typeof name === 'string'
  && /^[a-z0-9](?:[a-z0-9]|-(?=[a-z0-9])){0,38}$/.test(name);

export const CODEOWNERS_FILE = '.github/CODEOWNERS';
const BEGIN = '# BEGIN GENERATED by claude-code-web-users-support';
const END = '# END GENERATED by claude-code-web-users-support';

export function codeownersBlock(store, files) {
  const admin = `@${store.repo.split('/')[0]}`;
  const prefix = `${store.path}/`;
  const logins = [...new Set(files.filter((f) => f.startsWith(prefix) && f.slice(prefix.length).includes('/'))
    .map((f) => f.slice(prefix.length).split('/')[0]))].filter(isUsableIdentity).sort();
  return [
    BEGIN,
    `# from ${store.path}/ - regenerate with write_store_codeowners.mjs, never edit by hand`,
    `/${store.path}/ ${admin}`,
    ...logins.map((login) => `/${store.path}/${login}/ @${login} ${admin}`),
    `/${CODEOWNERS_FILE} ${admin}`,
    END,
  ].join('\n');
}

// The block and whatever owner lines follow it in `text`, or null when there is no block.
export function readBlock(text) {
  const start = text.indexOf(BEGIN);
  const end = start === -1 ? -1 : text.indexOf(END, start);
  if (end === -1) return null;
  const after = text.slice(end + END.length).split('\n').map((l) => l.trim()).filter((l) => l && !l.startsWith('#'));
  return { block: text.slice(start, end + END.length), start, end: end + END.length, ownerLinesAfter: after };
}

// `existing` with `block` in place: replaced where it stands, else appended.
export function withBlock(existing, block) {
  const text = existing ?? '';
  const found = readBlock(text);
  if (found) return `${text.slice(0, found.start)}${block}${text.slice(found.end)}`;
  return `${text}${text === '' || text.endsWith('\n') ? '' : '\n'}${block}\n`;
}
