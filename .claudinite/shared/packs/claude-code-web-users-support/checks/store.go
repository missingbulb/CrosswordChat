// Package checks holds claude-code-web-users-support's checks, which judge
// the personal-pack store a member names in this pack's config: that the
// address resolves, and, in the repo holding the store, its file names,
// its CODEOWNERS block and each rule's provenance marker.
package checks

import (
	"encoding/json"
	"regexp"
	"sort"
	"strings"

	"claudinite.com/checksdk"
)

const (
	pack           = "claude-code-web-users-support"
	defaultPath    = "preferences"
	codeownersFile = ".github/CODEOWNERS"
	blockBegin     = "# BEGIN GENERATED by claude-code-web-users-support"
	blockEnd       = "# END GENERATED by claude-code-web-users-support"
)

var (
	storeRepo = regexp.MustCompile(`^[^/\s]+\/[^/\s]+$`)
	pathTrim  = regexp.MustCompile(`^\./+|/+$`)
)

// store is a resolved personal-pack store: the repo holding it and the
// directory in it.
type store struct{ repo, path string }

// resolveStore reads the pack's config as store_codeowners.mjs does, and
// as the engine's session step does: ok is false when it names no usable
// store.
func resolveStore(raw json.RawMessage) (store, bool) {
	var config map[string]any
	if err := json.Unmarshal(raw, &config); err != nil || config == nil {
		return store{}, false
	}
	repo, ok := config["repo"].(string)
	if !ok || !storeRepo.MatchString(repo) {
		return store{}, false
	}
	path := defaultPath
	if v, set := config["path"]; set {
		p, ok := v.(string)
		if !ok || strings.Contains(p, "..") || strings.HasPrefix(p, "/") {
			return store{}, false
		}
		path = p
	}
	if path = pathTrim.ReplaceAllString(path, ""); path == "" {
		path = defaultPath
	}
	return store{repo: repo, path: path}, true
}

// usableIdentity is a name the reader can address: a GitHub login in
// lower case, 1 to 39 characters, a hyphen only between two others.
func usableIdentity(name string) bool {
	if len(name) == 0 || len(name) > 39 {
		return false
	}
	alnum := func(c byte) bool { return c >= 'a' && c <= 'z' || c >= '0' && c <= '9' }
	for i := 0; i < len(name); i++ {
		c := name[i]
		switch {
		case alnum(c):
		case c == '-' && i > 0 && i+1 < len(name) && alnum(name[i+1]):
		default:
			return false
		}
	}
	return true
}

// codeownersBlock is the CODEOWNERS block the store's person directories
// derive, as store_codeowners.mjs writes it.
func codeownersBlock(s store, files []string) string {
	admin := "@" + s.repo[:strings.Index(s.repo, "/")]
	prefix := s.path + "/"
	seen := map[string]bool{}
	var logins []string
	for _, f := range files {
		rest, ok := strings.CutPrefix(f, prefix)
		if !ok || !strings.Contains(rest, "/") {
			continue
		}
		login := rest[:strings.Index(rest, "/")]
		if !seen[login] && usableIdentity(login) {
			seen[login] = true
			logins = append(logins, login)
		}
	}
	sort.Strings(logins)
	lines := []string{blockBegin, "# from " + s.path + "/ - regenerate with write_store_codeowners.mjs, never edit by hand", "/" + s.path + "/ " + admin}
	for _, l := range logins {
		lines = append(lines, "/"+s.path+"/"+l+"/ @"+l+" "+admin)
	}
	return strings.Join(append(lines, "/"+codeownersFile+" "+admin, blockEnd), "\n")
}

// readBlock is the generated block in a CODEOWNERS text and the owner
// lines after it; ok is false when there is none.
func readBlock(text string) (block string, ownerLinesAfter []string, ok bool) {
	start := strings.Index(text, blockBegin)
	if start < 0 {
		return "", nil, false
	}
	end := strings.Index(text[start:], blockEnd)
	if end < 0 {
		return "", nil, false
	}
	end += start + len(blockEnd)
	for _, l := range strings.Split(text[end:], "\n") {
		if l = strings.TrimSpace(l); l != "" && !strings.HasPrefix(l, "#") {
			ownerLinesAfter = append(ownerLinesAfter, l)
		}
	}
	return text[start:end], ownerLinesAfter, true
}

// settingsFile is the member's settings file, where a finding about its
// pack entry points.
func settingsFile(repo checksdk.Repo) string {
	for _, f := range []string{".claudinite/settings.yaml", ".claudinite/settings.json", ".claudinite/settings.toml"} {
		if repo.Exists(f) {
			return f
		}
	}
	return ".claudinite/settings.yaml"
}

func has(xs []string, x string) bool {
	for _, y := range xs {
		if y == x {
			return true
		}
	}
	return false
}
